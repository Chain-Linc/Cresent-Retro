# This is only tested on windows powershell

import json
import subprocess
from PIL import Image
from pathlib import Path
import shutil

ART_FOLDER = "Art/"
RENDERED_FOLDER = "Tools/Rendered/"
SPRITS_FILEPATH = "ThumbyBattle/sprites.py"

INDEX_TRANSPARENT = 0
INDEX_OFFSET = -1
INDEX_BACKGROUND = 0

NIBBLE_TRANSPARENT = 15

def convertDash2CamelCase(varibleName):
    words = varibleName.split("-")
    ret = words[0].lower() + "".join(word.capitalize() for word in words[1:])
    return ret

def pixels2Bytearray(pixels):
    # bytearray = [0x00, 0x01, 0x02... ]
    pairsPerByte = 2
    pixelsPaired = []
    
    # pair pixels
    for i in range(0, len(pixels), pairsPerByte):
        pixelsPaired.append([])
        for j in range(pairsPerByte):
            index = i + j
            if index < len(pixels):
                pixelsPaired[-1].append(pixels[i+j])
            else:
                pixelsPaired[-1].append(0)

    # convert pairs to numbers
    bytes = []
    for pair in pixelsPaired:
        byte = 0
        for number in pair:
            byte = (byte << number) | 4
        bytes.append(byte)

    # convert numbers into list
    retBytearray = "["
    for byte in bytes:
        retBytearray += str(byte) + ","
    retBytearray = retBytearray[:-2] + "]"

    return retBytearray

def pillow2Bytearray(file):
    flatSequenceRaw = [i for i in file.get_flattened_data()]

    pixles = []
    for pixel in flatSequenceRaw:
        # if transparent
        if pixel == INDEX_TRANSPARENT:
            pixles.append(NIBBLE_TRANSPARENT)
        else: # if not transparent
            pixles.append(pixel+INDEX_OFFSET)

    return pixels2Bytearray(pixles)


print("Started converting")

with open("Tools/convertArtImport.json", "r") as list:
    fileList = json.load(list)

print("Convert list loaded")

if Path(RENDERED_FOLDER).exists():
    shutil.rmtree(Path(RENDERED_FOLDER))

Path(RENDERED_FOLDER).mkdir(parents=True, exist_ok=True)

varibleNames = []

saveFileList = []
for filepath in fileList:
    getFilePath = ART_FOLDER + filepath
    saveFilePath = RENDERED_FOLDER + filepath.removesuffix(".aseprite")
    subprocess.run(["aseprite", "-b", "--color-mode", "indexed", getFilePath, "--save-as", saveFilePath + "-1.png"])
    print(getFilePath, "is aseprite processed and saved to:", saveFilePath)

    varibleNames.append(filepath.removesuffix(".aseprite"))
    
    fileSet = []
    i = 1
    while True:
        file = Path(saveFilePath + "-" + str(i) + ".png")
        if file.is_file():
            fileSet.append(file)
            i += 1
        else:
            break
    
    if len(fileSet) == 0:
        print(f"error: no file generated to {saveFilePath}")
    elif len(fileSet) == 1:
        fileSet[0] = fileSet[0][:-4] + ".png"
    else:
        saveFileList.append(fileSet)

print("All files aseprite processed")

fileText = "# This file is automatically generated\nfrom engine import Surface, Sprite\n"
for i, filePathSet in enumerate(saveFileList):
    names = []
    for filePath in filePathSet:
        pillowFile = Image.open(filePath)
        pixels = pillow2Bytearray(pillowFile)
        name = convertDash2CamelCase(Path(filePath).stem)
        print(name)

        fileWidth = pillowFile.width
        fileHeight = pillowFile.height

        spriteText = f"{name} = Surface(bytearray({pixels}), {fileWidth}, {fileHeight})"
        names.append(name)

        fileText = f"{fileText}\n{spriteText}"
    
    if len(names) > 2:
        animatedSpriteText = f"{convertDash2CamelCase(varibleNames[i])} = Sprite([{', '.join(names)}])"
        fileText = f"{fileText}\n\n{animatedSpriteText}\n"


print("All varibles written")

with open(SPRITS_FILEPATH, "w") as f:
    f.write(fileText)

print("sprite.py saved")
print("Done!")